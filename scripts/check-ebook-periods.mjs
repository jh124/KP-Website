import assert from "node:assert/strict";
import { calendarPeriod, createDownloadHistory, recordDownloadSnapshot, periodDownloadCounts, reportDateKey } from "../assets/ebook-history.js";

const asset = (id, name, count) => ({ id, name, download_count: count, state: "uploaded" });
const books = [{ title: "Example", pdf: "example.pdf", epub: "example.epub" }];
const make = (pdf, epub, second = 0) => [asset(764644766, "example.pdf", pdf), asset(764644733, "example.epub", epub), ...(second ? [asset(900000001, "example.pdf", second)] : [])];
let history = createDownloadHistory("2026-11-18T19:11:37Z");
history = recordDownloadSnapshot(history, make(5, 2), "2026-11-18T23:00:00Z");
assert.equal(periodDownloadCounts(books, make(5, 2), history, "today", "2026-11-18T23:00:00Z")[0].total, 3);
const again = recordDownloadSnapshot(history, make(5, 2), "2026-11-19T00:00:00Z");
assert.equal(again, history, "An unchanged observation on the same Eastern date must not create another commit.");
history = recordDownloadSnapshot(history, make(6, 4), "2026-11-19T05:01:00Z");
assert.equal(periodDownloadCounts(books, make(7, 4), history, "today", "2026-11-19T05:02:00Z")[0].total, 4);
assert.equal(periodDownloadCounts(books, make(7, 4), history, "all", "2026-11-19T05:02:00Z")[0].total, 7);
assert.equal(history.assets[764644766].count, 6, "Live previews must not mutate saved history.");
history = recordDownloadSnapshot(history, make(8, 4, 3), "2026-11-22T05:01:00Z");
assert.equal(periodDownloadCounts(books, make(8, 4, 3), history, "week", "2026-11-22T05:01:00Z")[0].total, 5);
assert.equal(periodDownloadCounts(books, make(8, 4, 3), history, "month", "2026-11-22T05:01:00Z")[0].total, 11);
history = recordDownloadSnapshot(history, make(10, 5, 3), "2026-12-01T05:01:00Z");
assert.equal(periodDownloadCounts(books, make(10, 5, 3), history, "month", "2026-12-01T05:01:00Z")[0].total, 3);
assert.equal(periodDownloadCounts(books, make(10, 5, 3), history, "all", "2026-12-01T05:01:00Z")[0].total, 14);
assert.equal(recordDownloadSnapshot(history, make(1, 1, 1), "2026-12-01T06:00:00Z"), history, "Older cached counters cannot erase counts or cause them to be counted twice later.");
assert.equal(periodDownloadCounts(books, make(1, 1, 1), history, "all", "2026-12-01T06:00:00Z")[0].total, 14);
assert.equal(calendarPeriod("week", "2027-01-01T17:00:00Z").startDate, "2026-12-27");
assert.equal(calendarPeriod("month", "2028-02-29T17:00:00Z").endDate, "2028-02-29");
assert.equal(calendarPeriod("today", "2026-12-01T04:59:59Z").startDate, "2026-11-30");
assert.equal(calendarPeriod("today", "2026-12-01T05:00:00Z").startDate, "2026-12-01");
assert.equal(reportDateKey("2027-03-14T04:59:59Z"), "2027-03-13");
assert.equal(reportDateKey("2027-03-15T03:59:59Z"), "2027-03-14");
assert.equal(reportDateKey("2027-03-15T04:00:00Z"), "2027-03-15");
assert.equal(reportDateKey("2026-11-01T05:30:00Z"), "2026-11-01");
assert.equal(reportDateKey("2026-11-01T06:30:00Z"), "2026-11-01");
assert.throws(() => periodDownloadCounts(books, make(5, 2), null, "today"), /unavailable/);
assert.throws(() => recordDownloadSnapshot(createDownloadHistory("2026-11-18T19:11:37Z"), make(5, 2), "2026-11-19T12:00:00Z"), /cannot be reconstructed/);
assert.equal(periodDownloadCounts(books, make(5, 2), null, "all")[0].total, 3);
assert.equal(calendarPeriod("week", "2026-11-22T04:59:59Z").startDate, "2026-11-15");
assert.equal(calendarPeriod("week", "2026-11-22T05:00:00Z").startDate, "2026-11-22");
console.log("Checked calendar months, Sunday weeks, Eastern midnight, both DST changes, saved snapshots, edition changes, excluded setup tests, stale API counters, and live increments.");
